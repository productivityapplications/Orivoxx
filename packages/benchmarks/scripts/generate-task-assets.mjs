import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const tasksRoot = join(packageRoot, "src", "tasks");

const EXCLUDED_FILES = new Set(["fixture.manifest.json"]);

async function listFiles(root, current = root) {
  const entries = await readdir(current, { withFileTypes: true });
  const files = [];

  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    const absolute = join(current, entry.name);

    if (entry.isDirectory()) {
      files.push(...(await listFiles(root, absolute)));
      continue;
    }

    if (!entry.isFile() || EXCLUDED_FILES.has(entry.name)) {
      continue;
    }

    const path = relative(root, absolute).split("\\").join("/");
    const content = await readFile(absolute, "utf8");

    files.push({ path, content });
  }

  return files.sort((left, right) => left.path.localeCompare(right.path));
}

function emit(prefix, specText, startingFiles, compliantFiles, regressedFiles) {
  const lines = [
    "// Generated by scripts/generate-task-assets.mjs. Do not edit by hand.",
    'import type { ProjectFile } from "@orivoxx/core";',
    "",
    `export const ${prefix}_SPEC_TEXT = ${JSON.stringify(specText)};`,
    "",
    `export const ${prefix}_STARTING_FILES: ProjectFile[] = ${JSON.stringify(startingFiles, null, 2)};`,
    "",
    `export const ${prefix}_COMPLIANT_FILES: ProjectFile[] = ${JSON.stringify(compliantFiles, null, 2)};`,
    "",
    `export const ${prefix}_REGRESSED_FILES: ProjectFile[] = ${JSON.stringify(regressedFiles, null, 2)};`,
    "",
  ];

  return lines.join("\n");
}

async function generateTask(id, prefix) {
  const root = join(tasksRoot, id);
  const specText = await readFile(join(root, "PROJECT_SPEC.md"), "utf8");
  const starting = await listFiles(join(root, "starting"));

  if (!starting.some((file) => file.path === "PROJECT_SPEC.md")) {
    starting.unshift({ path: "PROJECT_SPEC.md", content: specText });
  }

  const compliant = await listFiles(join(root, "fixtures", "compliant"));
  const regressed = await listFiles(join(root, "fixtures", "regressed"));

  const output = emit(prefix, specText, starting, compliant, regressed);
  const target = join(root, "generated.ts");

  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, output, "utf8");
  console.log(
    `generated ${relative(packageRoot, target)} (${starting.length} starting, ${compliant.length} compliant, ${regressed.length} regressed)`,
  );
}

await generateTask("taskboard", "TASKBOARD");
await generateTask("linkstash", "LINKSTASH");
